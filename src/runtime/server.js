/**
 * Production entry around adapter-node's generated server. It resolves every
 * request to a configured browser-facing origin before the official handler
 * constructs SvelteKit's Request, while retaining adapter-node's listener and
 * graceful shutdown behavior.
 */
import process from 'node:process';
import { parseOrigins, resolveOrigin } from './origins.js';

const PROTOCOL_HEADER = 'x-profilarr-origin-protocol';
const HOST_HEADER = 'x-profilarr-origin-host';

let origins;
try {
	origins = parseOrigins(process.env.ORIGIN);
} catch (error) {
	console.error(error instanceof Error ? error.message : String(error));
	process.exit(1);
}

// adapter-node reads these once while its generated handler is imported.
process.env.PROTOCOL_HEADER = PROTOCOL_HEADER;
process.env.HOST_HEADER = HOST_HEADER;
delete process.env.PORT_HEADER;
delete process.env.ADDRESS_HEADER;

// Profilarr's backup endpoint accepts files up to 1 GiB. Leave room for the
// multipart envelope while allowing an operator to choose a lower limit.
process.env.BODY_SIZE_LIMIT ||= '1025M';

// How long adapter-node waits for open connections after SIGTERM. Its 30 s
// default outlasts Docker's 10 s stop grace whenever a job progress stream is
// open, so the process would be killed instead. 5 s lets page requests finish;
// the stream is cut and the browser reconnects.
process.env.SHUTDOWN_TIMEOUT ||= '5';

// Generated by adapter-node beside this copied entry point; typed by index.d.ts.
// eslint-disable-next-line profilarr/import-paths -- the build writes it next to the copied entry
const { server } = await import('./index.js');

// adapter-node closes its listener on SIGTERM and SIGINT, then emits this once
// in-flight requests have drained. Profilarr's job timers keep the event loop
// alive, so exit explicitly or the container would wait for Docker's SIGKILL.
process.once('sveltekit:shutdown', () => process.exit(0));

// Resolve each request's browser-facing origin before adapter-node's handler
// builds SvelteKit's Request from the private headers set above.
const handlers = server.listeners('request');
server.removeAllListeners('request');
server.on(
	'request',
	/**
	 * @param {import('node:http').IncomingMessage} request
	 * @param {import('node:http').ServerResponse} response
	 */
	(request, response) => {
		delete request.headers[PROTOCOL_HEADER];
		delete request.headers[HOST_HEADER];
		const encrypted =
			/** @type {{ encrypted?: boolean }} */ (/** @type {unknown} */ (request.socket)).encrypted ===
			true;
		const origin = resolveOrigin(request.headers, encrypted, origins);
		if (!origin) {
			// HTTP/1.1 requires a Host; adapter-node would reject this too
			response.writeHead(400, { 'content-type': 'text/plain' }).end('Bad Request');
			return;
		}
		const url = new URL(origin);
		request.headers[PROTOCOL_HEADER] = url.protocol.slice(0, -1);
		request.headers[HOST_HEADER] = url.host;
		for (const handler of handlers) handler.call(server, request, response);
	}
);
